// TypeScript Tuples

// Create a tuple with string and number data
let person: [string, number] = ["Alice", 25];
console.log(person);

// Output: [ 'Alice', 25 ]


// Change Tuple Elements
// Create a tuple with string and number data
let personn: [string, number] = ["Alice", 25];

// Print the tuple
console.log(personn);

// Change the first element
personn[0] = "Veronica";

// Print the changed tuple
console.log(personn);

// Assign new values to the entire tuple
personn = ["Brad", 39];

// Print the changed tuple
console.log(personn);
